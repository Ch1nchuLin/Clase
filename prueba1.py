# calculando el area de un cirtulo 

radioInpt = float(input("ingrese el radio del circulo "))
area = (3.14 * ((radioInpt)**2))

print ("El area del circulo es: " + str(area)) 

# calculando el area de un triangulo pidiendo base y altura
trianguloBaseInpt = float(input("ingrese la Base de el triangulo "))
trainguloAlturaInpt = float(input("ingrese la Altura de el triangulo "))

print ("El area de el triangulo es: " + str(trianguloBaseInpt * trainguloAlturaInpt))

# calculando el area de un cuadrado pidiendo un valor de sus lados

LadoCuadrado = float(input("ingrese el lado de su cuadrado para calcular el area "))
print ("El area de el cuadrado es: " + str(LadoCuadrado*LadoCuadrado))



